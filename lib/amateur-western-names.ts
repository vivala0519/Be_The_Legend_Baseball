export function getWesternKoreanAliases(country: WesternAmateurCountry, originalName: string): string[] {
  const koreanName = getWesternKoreanName(country, originalName);
  if (country === "US") {
    const aliases: string[] = [];
    for (const [standard, variant] of usSpellingVariants) {
      if (koreanName.includes(standard)) aliases.push(koreanName.replace(standard, variant));
    }
    return aliases;
  }
  const aliases = [...(academySpellingVariants.get(originalName) ?? [])];
  if (koreanName.includes("야구 아카데미")) aliases.push(koreanName.replace("야구 아카데미", "베이스볼 아카데미"));
  return aliases;
}
